/**
 * Security store (Phase 5): what the verification banner, the emoji (SAS) dialog, the recovery-key entry and
 * the first-time setup dialog render, plus the actions behind their buttons. Thin state over
 * `src/lib/matrix/security.ts`; nothing here talks to the SDK directly except the event subscriptions in
 * `bindSecurity`.
 *
 *   status        this device: verified? identity exists? recovery key exists? backup?   (`refresh()`)
 *   hint          what to nag about: 'setup' | 'verify' | 'unlock' | null                 (derived, see `securityHint`)
 *   verification  the in-flight SAS flow (ours or incoming), with `sas.emoji` once both sides agreed
 *   recovery      busy / progress / error of unlock, restore, setup and key-file import, and `backupLocked`:
 *                 verified, but the key backup could not be opened (its key sits under another recovery key, the
 *                 prompt was cancelled); `lastImport` / `importError` of `importKeysFromFile` (an Element key export)
 *   keysImported  a key file was imported this session (the banner then stops nagging about `unlock`)
 *   historyUnavailable  verified, but no way to the backup key: none cached, nothing gossiped within
 *                 `GOSSIP_GRACE_MS` of a verification done on this page (none when the device was already verified
 *                 at page load), and the 4S copy is not under the default key (only under a
 *                 recovery key the account no longer uses). The UI then offers one plain state (import a key file /
 *                 a different recovery key) instead of asking for the recovery key again; `historyChecked` says
 *                 the check resolved (until then the banner stays quiet)
 *
 * Self-heal: after an unlock, a completed self-verification, a successful restore or import, `healKeyStorage()`
 * silently re-stores locally held secrets (cross-signing keys, backup key) that 4S lacks under the default key
 * (`syncSecretsToDefaultKey`); it never creates or resets keys.
 *   prompt        a question the SDK or a flow needs answered *now* (password for UIA, recovery key); render a
 *                 dialog while non-null and call `answerPrompt(value | null)`. One ask only: the recovery-key prompt
 *                 is registered with crypto.ts only inside `restoreWithDifferentKey()` (the explicit "I have a
 *                 different recovery key"); anywhere else a secret no cached key opens fails the call with
 *                 `SecretStorageKeyMissError` and lands on `recovery.backupLocked`, never on a prompt
 *   newRecoveryKey the key generated by `setupRecovery`, to display once; `dismissRecoveryKey()` clears it
 *
 * Session wiring: `bindSecurity(client)` after `bindClient`, `unbindSecurity()` + `resetSecurity()` on logout
 * (session.ts does both). Crypto events (keys changed, backup status, incoming requests) refresh the snapshot.
 */
