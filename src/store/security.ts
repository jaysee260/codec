let unbind: (() => void) | null = null;

/** Subscribe to crypto events for a started client and take the first status snapshot. Idempotent per client. */
export function bindSecurity(client: MatrixClient): void {
  unbindSecurity();
  const store = useSecurityStore.getState();
  // The SDK asks for the recovery key when it reads secret storage and nothing is cached: route it to the prompt.
  setSecretStorageKeyPrompt(() => ask('recovery-key', 'Enter your recovery key to unlock your encryption keys'));
  const refresh = (): void => void useSecurityStore.getState().refresh();
  const onRequest = (request: VerificationRequest): void => {
    // One flow at a time: a new incoming request replaces whatever is tracked. An active flow is cancelled first
    // (AC-E4-7: the latest request wins, the stale one never leaves a dangling dialog); a finished one is dropped.
    const current = useSecurityStore.getState().verification;
    const active = !!current && current.stage !== 'done' && current.stage !== 'cancelled';
    // The Rust engine refuses a second concurrent request from the same user: it arrives already cancelled. Keep
    // the live flow then (tracking the dead one would lose both).
    if (active && request.phase === VerificationPhase.Cancelled) return;
    if (active) {
      const stale = live;
      live = null;
      stale?.off();
      void stale?.request.cancel().catch(() => {
        /* already gone */
      });
    }
    trackRequest(request);
  };
  const onBackupKeyCached = (): void => {
    // The device that verified us (or the unlock flow) just handed us the backup key: fetch old room keys.
    void useSecurityStore.getState().restoreFromBackup();
  };
  // Cross-signing / backup state is only known once the first /sync (and the key query it triggers) landed.
  const onSync = (state: SyncState): void => {
    if (state === SyncState.Prepared) refresh();
  };
  const offRequest = onVerificationRequestReceived(onRequest);
  client.on(ClientEvent.Sync, onSync);
  client.on(CryptoEvent.KeysChanged, refresh);
  client.on(CryptoEvent.UserTrustStatusChanged, refresh);
  client.on(CryptoEvent.DevicesUpdated, refresh);
  const onRemaining = (remaining: number): void => {
    useSecurityStore.setState((s) => (s.backupRemaining === remaining ? s : { backupRemaining: remaining, version: s.version + 1 }));
  };
  client.on(CryptoEvent.KeyBackupStatus, refresh);
  client.on(CryptoEvent.KeyBackupSessionsRemaining, onRemaining);
  client.on(CryptoEvent.KeyBackupDecryptionKeyCached, onBackupKeyCached);
  unbind = () => {
    offRequest();
    client.off(ClientEvent.Sync, onSync);
    client.off(CryptoEvent.KeysChanged, refresh);
    client.off(CryptoEvent.UserTrustStatusChanged, refresh);
    client.off(CryptoEvent.DevicesUpdated, refresh);
    client.off(CryptoEvent.KeyBackupStatus, refresh);
    client.off(CryptoEvent.KeyBackupSessionsRemaining, onRemaining);
    client.off(CryptoEvent.KeyBackupDecryptionKeyCached, onBackupKeyCached);
    setSecretStorageKeyPrompt(null);
  };
  void store.refresh();
}

export function unbindSecurity(): void {
  unbind?.();
  unbind = null;
}

/** Logout: forget flows, prompts and status. */
export function resetSecurity(): void {
  live?.off();
  live = null;
  pendingPromptResolve?.(null);
  pendingPromptResolve = null;
  useSecurityStore.setState((s) => ({
    cryptoReady: false,
    cryptoError: null,
    status: null,
    hint: null,
    verification: null,
    recovery: idleRecovery,
    prompt: null,
    newRecoveryKey: null,
    backupRemaining: null,
    version: s.version + 1,
  }));
}

/** Selector: the banner hint (`'setup' | 'verify' | 'unlock' | null`). */
export function useSecurityHint(): SecurityHint {
  return useSecurityStore((s) => s.hint);
}
