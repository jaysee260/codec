/**
 * Security store (Phase 5): what the verification banner, the emoji (SAS) dialog, the recovery-key entry and
 * the first-time setup dialog render, plus the actions behind their buttons. Thin state over
 * `src/lib/matrix/security.ts`; nothing here talks to the SDK directly except the event subscriptions in
 * `bindSecurity`.
 *
 *   status        this device: verified? identity exists? recovery key exists? backup?   (`refresh()`)
 *   hint          what to nag about: 'setup' | 'verify' | 'unlock' | null                 (derived, see `securityHint`)
 *   verification  the in-flight SAS flow (ours or incoming), with `sas.emoji` once both sides agreed
 *   recovery      busy / progress / error of unlock, restore and setup
 *   prompt        a question the SDK or a flow needs answered *now* (password for UIA, recovery key); render a
 *                 dialog while non-null and call `answerPrompt(value | null)`
 *   newRecoveryKey the key generated by `setupRecovery`, to display once; `dismissRecoveryKey()` clears it
 *
 * Session wiring: `bindSecurity(client)` after `bindClient`, `unbindSecurity()` + `resetSecurity()` on logout
 * (session.ts does both). Crypto events (keys changed, backup status, incoming requests) refresh the snapshot.
 */
import { create } from 'zustand';
import { ClientEvent, SyncState, type MatrixClient } from 'matrix-js-sdk';
import { CryptoEvent, type ImportRoomKeyProgressData } from 'matrix-js-sdk/lib/crypto-api/index.js';
import {
  VerificationPhase,
  VerificationRequestEvent,
  VerifierEvent,
  type ShowSasCallbacks,
  type VerificationRequest,
  type Verifier,
} from 'matrix-js-sdk/lib/crypto-api/verification.js';
import { getCryptoError, setSecretStorageKeyPrompt } from '@/lib/matrix/crypto.ts';
import {
  getOwnDeviceStatus,
  isCryptoReady,
  RecoveryKeyError,
  onVerificationRequestReceived,
  requestOwnUserVerification,
  restoreFromBackup,
  setupRecovery,
  startSas,
  unlockWithRecoveryKey,
  type OwnDeviceStatus,
  type UiaOptions,
} from '@/lib/matrix/security.ts';

export type SecurityHint = 'setup' | 'verify' | 'unlock' | null;

export type VerificationStage = 'requested' | 'ready' | 'started' | 'sas' | 'done' | 'cancelled';

export interface SasState {
  /** Seven `[emoji, name]` pairs to compare with the other device. */
  emoji: [string, string][];
  decimal?: [number, number, number];
}

export interface VerificationFlow {
  stage: VerificationStage;
  /** We sent the request (banner "Verify this session"), else it arrived from another device / user. */
  initiatedByMe: boolean;
  /** Verifying our own account's other device (the normal case), vs another user. */
  isSelf: boolean;
  otherUserId: string;
  otherDeviceId?: string;
  sas: SasState | null;
  /** Why it stopped (cancel code / message) when `stage === 'cancelled'`. */
  error: string | null;
}

export interface RecoveryState {
  busy: 'unlock' | 'restore' | 'setup' | null;
  progress: { imported: number; total: number } | null;
  lastRestore: { imported: number; total: number } | null;
  error: string | null;
  /**
   * Set with `error` when `unlockWithRecoveryKey` failed on the key itself (`RecoveryKeyError.kind`): `none` = the
   * account has no recovery key, `invalid` = not a recovery key / passphrase shape, `wrong` = does not open the
   * secret storage. Undefined for any other failure (network, backup) so the UI never matches message text.
   */
  errorKind?: 'none' | 'invalid' | 'wrong';
}

export interface PendingPrompt {
  /**
   * `password`: the server wants `m.login.password` for a UIA stage (answer with the password);
   * `recovery-key`: the SDK needs the secret storage key (answer with the key / passphrase);
   * `sso`: SSO-only servers (704.chat): the `m.login.sso` fallback page opened in a popup (`url`; `popupBlocked`
   * when it could not open, so show the link). Render "Finish signing in in the window that opened" and a
   * "Done" button that calls `answerPrompt('done')`; the prompt also closes by itself when the popup reports back.
   */
  kind: 'password' | 'recovery-key' | 'sso';
  /** Human text for the dialog ("Confirm your password to upload your keys"). */
  message: string;
  /** `sso` only: the fallback page URL. */
  url?: string;
  /** `sso` only: the popup was blocked; the UI should offer `url` as a link. */
  popupBlocked?: boolean;
}

export interface SecurityState {
  /** The crypto engine runs for this session (false before bind, or when it failed: see `cryptoError`). */
  cryptoReady: boolean;
  cryptoError: string | null;
  /** Null until the first `refresh()` completes. */
  status: OwnDeviceStatus | null;
  hint: SecurityHint;
  verification: VerificationFlow | null;
  recovery: RecoveryState;
  prompt: PendingPrompt | null;
  newRecoveryKey: string | null;
  /**
   * Room keys this device still has to upload to the key backup (`CryptoEvent.KeyBackupSessionsRemaining`);
   * null until the first upload round. The SDK starts uploading up to 10 s after the backup is enabled, so a
   * logout right after `setupRecovery` can leave keys out of the backup: show "Backing up N keys" while > 0.
   */
  backupRemaining: number | null;
  /** Bumps on every change the UI might care about (status, flow, prompt). */
  version: number;

  /** Re-read this device's status from the SDK. */
  refresh(): Promise<void>;
  /** Banner button: ask the account's other devices (Element, another codec) to verify this one by emoji. */
  startSelfVerification(): Promise<void>;
  /** Accept an incoming request (`verification.initiatedByMe === false`, stage 'requested'). */
  acceptVerification(): Promise<void>;
  /** Cancel / decline the in-flight request. */
  cancelVerification(): Promise<void>;
  /** The emoji match. */
  confirmSas(): Promise<void>;
  /** The emoji do not match (cancels with `m.mismatched_sas`). */
  mismatchSas(): void;
  /** Drop a finished / cancelled flow from the state. */
  dismissVerification(): void;
  /** Recovery key (or passphrase) typed by the user: verifies this device from secret storage and restores backup. */
  unlockWithRecoveryKey(input: string): Promise<boolean>;
  /** Pull room keys from the key backup (the decryption key must be known: after SAS or unlock). */
  restoreFromBackup(): Promise<void>;
  /** First-time setup (or `reset`): creates cross-signing, a recovery key and a key backup. Resolves with the key. */
  setupRecovery(opts?: { passphrase?: string; reset?: boolean }): Promise<string | null>;
  dismissRecoveryKey(): void;
  /** Answer the current `prompt` (null = cancel). */
  answerPrompt(value: string | null): void;
}

const idleRecovery: RecoveryState = { busy: null, progress: null, lastRestore: null, error: null };

/** What to show the user given a status snapshot. */
export function securityHint(status: OwnDeviceStatus | null): SecurityHint {
  if (!status) return null;
  // No identity and no recovery key: first-time setup. With a recovery key but no identity (AC-E5-5: a reset
  // account, or keys created by another client), the key is the way in: `unlockWithRecoveryKey` bootstraps
  // cross-signing from (or into) secret storage.
  if (!status.hasCrossSigningKeys) return status.secretStorageReady ? 'unlock' : 'setup';
  if (!status.verified) return 'verify';
  if (status.backup.version && !status.backup.keyCached) return 'unlock';
  return null;
}

function describe(e: unknown): string {
  return e instanceof Error ? e.message : String(e);
}

/** The live request/verifier behind `verification` (not in the store: not serialisable, not for rendering). */
let live: { request: VerificationRequest; verifier?: Verifier; sas?: ShowSasCallbacks; off: () => void } | null = null;
let pendingPromptResolve: ((value: string | null) => void) | null = null;

function ask(kind: PendingPrompt['kind'], message: string, extra: Partial<PendingPrompt> = {}): Promise<string | null> {
  pendingPromptResolve?.(null);
  return new Promise((resolve) => {
    pendingPromptResolve = resolve;
    useSecurityStore.setState((s) => ({ prompt: { kind, message, ...extra }, version: s.version + 1 }));
  });
}

/** Clear the current prompt without answering it (the flow finished on its own, e.g. the SSO popup reported back). */
function dropPrompt(): void {
  pendingPromptResolve = null;
  useSecurityStore.setState((s) => (s.prompt ? { prompt: null, version: s.version + 1 } : s));
}

const uia: UiaOptions = {
  password: () => ask('password', 'Confirm your password to publish your encryption keys'),
  sso: async (url, popupBlocked) => {
    const answer = await ask('sso', popupBlocked ? 'Open the sign-in page, finish signing in, then come back' : 'Finish signing in in the window that opened', { url, popupBlocked });
    if (answer === null) throw new Error('Authentication cancelled');
  },
};

function flowFrom(request: VerificationRequest, prev?: VerificationFlow | null): VerificationFlow {
  const stage: VerificationStage =
    request.phase === VerificationPhase.Done
      ? 'done'
      : request.phase === VerificationPhase.Cancelled
        ? 'cancelled'
        : request.phase === VerificationPhase.Started
          ? (prev?.sas ? 'sas' : 'started')
          : request.phase === VerificationPhase.Ready
            ? 'ready'
            : 'requested';
  return {
    stage,
    initiatedByMe: request.initiatedByMe,
    isSelf: request.isSelfVerification,
    otherUserId: request.otherUserId,
    otherDeviceId: request.otherDeviceId ?? prev?.otherDeviceId, // the SDK drops it once the request is done
    sas: stage === 'sas' ? (prev?.sas ?? null) : null,
    error:
      stage === 'cancelled'
        ? (prev?.error ?? (request.cancellationCode === 'm.mismatched_sas' ? 'The emoji did not match' : request.cancellationCode === 'm.timeout' ? 'The request timed out' : `Cancelled (${request.cancellationCode ?? 'unknown'})`))
        : null,
  };
}

function setFlow(flow: VerificationFlow | null): void {
  useSecurityStore.setState((s) => ({ verification: flow, version: s.version + 1 }));
}

/** Track a request: mirror its phases, start SAS when both sides are ready, surface the emoji. */
function trackRequest(request: VerificationRequest): void {
  live?.off();
  let verifierAttached = false;
  let starting = false;
  const attachVerifier = (verifier: Verifier): void => {
    if (verifierAttached) return;
    verifierAttached = true;
    live!.verifier = verifier;
    verifier.on(VerifierEvent.ShowSas, (sas) => {
      live!.sas = sas;
      const prev = useSecurityStore.getState().verification;
      setFlow({ ...flowFrom(request, prev), stage: 'sas', sas: { emoji: sas.sas.emoji ?? [], decimal: sas.sas.decimal } });
    });
    verifier.on(VerifierEvent.Cancel, (e) => {
      const prev = useSecurityStore.getState().verification;
      setFlow({ ...flowFrom(request, prev), stage: 'cancelled', error: e instanceof Error ? e.message : (prev?.error ?? 'Cancelled by the other device') });
    });
    verifier.verify().catch(() => {
      /* reported through VerifierEvent.Cancel / the request phase */
    });
  };
  const onChange = (): void => {
    const prev = useSecurityStore.getState().verification;
    setFlow(flowFrom(request, prev));
    if (request.verifier) attachVerifier(request.verifier);
    if (request.phase === VerificationPhase.Ready && !request.verifier && !starting) {
      starting = true;
      startSas(request)
        .then(attachVerifier)
        .catch((e: unknown) => setFlow({ ...flowFrom(request, prev), stage: 'cancelled', error: describe(e) }));
    }
    if (request.phase === VerificationPhase.Done) void useSecurityStore.getState().refresh();
  };
  request.on(VerificationRequestEvent.Change, onChange);
  live = { request, off: () => request.off(VerificationRequestEvent.Change, onChange) };
  onChange();
}

export const useSecurityStore = create<SecurityState>((set, get) => ({
  cryptoReady: false,
  cryptoError: null,
  status: null,
  hint: null,
  verification: null,
  recovery: idleRecovery,
  prompt: null,
  newRecoveryKey: null,
  backupRemaining: null,
  version: 0,

  async refresh() {
    if (!isCryptoReady()) {
      set((s) => ({ cryptoReady: false, cryptoError: getCryptoError(), status: null, hint: null, version: s.version + 1 }));
      return;
    }
    try {
      const status = await getOwnDeviceStatus();
      set((s) => ({ cryptoReady: true, cryptoError: null, status, hint: securityHint(status), version: s.version + 1 }));
    } catch (e) {
      console.warn('[security] status refresh failed', e);
    }
  },

  async startSelfVerification() {
    try {
      const request = await requestOwnUserVerification();
      trackRequest(request);
    } catch (e) {
      setFlow({ stage: 'cancelled', initiatedByMe: true, isSelf: true, otherUserId: '', sas: null, error: describe(e) });
    }
  },

  async acceptVerification() {
    if (!live) return;
    try {
      await live.request.accept();
    } catch (e) {
      setFlow({ ...flowFrom(live.request, get().verification), stage: 'cancelled', error: describe(e) });
    }
  },

  async cancelVerification() {
    if (!live) return;
    try {
      await live.request.cancel({ reason: 'User cancelled', code: 'm.user' });
    } catch {
      /* already over */
    }
  },

  async confirmSas() {
    const sas = live?.sas;
    if (!sas) return;
    try {
      await sas.confirm();
    } catch (e) {
      if (live) setFlow({ ...flowFrom(live.request, get().verification), stage: 'cancelled', error: describe(e) });
    }
  },

  mismatchSas() {
    live?.sas?.mismatch();
  },

  dismissVerification() {
    live?.off();
    live = null;
    setFlow(null);
  },

  async unlockWithRecoveryKey(input) {
    set((s) => ({ recovery: { ...idleRecovery, busy: 'unlock' }, version: s.version + 1 }));
    try {
      const result = await unlockWithRecoveryKey(input, { uia, onProgress: (p) => reportProgress(p) });
      dropPrompt();
      set((s) => ({ recovery: { ...idleRecovery, lastRestore: result }, version: s.version + 1 }));
      await get().refresh();
      return true;
    } catch (e) {
      dropPrompt();
      const errorKind = e instanceof RecoveryKeyError ? e.kind : undefined;
      set((s) => ({ recovery: { ...idleRecovery, error: describe(e), ...(errorKind ? { errorKind } : {}) }, version: s.version + 1 }));
      return false;
    }
  },

  async restoreFromBackup() {
    if (get().recovery.busy) return;
    set((s) => ({ recovery: { ...idleRecovery, busy: 'restore' }, version: s.version + 1 }));
    try {
      const result = await restoreFromBackup((p) => reportProgress(p));
      set((s) => ({ recovery: { ...idleRecovery, lastRestore: result }, version: s.version + 1 }));
    } catch (e) {
      set((s) => ({ recovery: { ...idleRecovery, error: describe(e) }, version: s.version + 1 }));
    }
    await get().refresh();
  },

  async setupRecovery(opts = {}) {
    set((s) => ({ recovery: { ...idleRecovery, busy: 'setup' }, newRecoveryKey: null, version: s.version + 1 }));
    try {
      const key = await setupRecovery({ ...opts, uia });
      dropPrompt();
      set((s) => ({ recovery: idleRecovery, newRecoveryKey: key, version: s.version + 1 }));
      await get().refresh();
      return key;
    } catch (e) {
      dropPrompt();
      set((s) => ({ recovery: { ...idleRecovery, error: describe(e) }, version: s.version + 1 }));
      return null;
    }
  },

  dismissRecoveryKey() {
    set((s) => ({ newRecoveryKey: null, version: s.version + 1 }));
  },

  answerPrompt(value) {
    const resolve = pendingPromptResolve;
    pendingPromptResolve = null;
    set((s) => ({ prompt: null, version: s.version + 1 }));
    resolve?.(value);
  },
}));

function reportProgress(p: ImportRoomKeyProgressData): void {
  if (p.stage !== 'load_keys') return;
  useSecurityStore.setState((s) => ({
    recovery: { ...s.recovery, progress: { imported: p.successes, total: p.total } },
    version: s.version + 1,
  }));
}

