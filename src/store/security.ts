export type SecurityHint = 'setup' | 'verify' | 'unlock' | null;

export type VerificationStage = 'requested' | 'ready' | 'started' | 'sas' | 'done' | 'cancelled';

export interface SasState {
  /** Seven `[emoji, name]` pairs to compare with the other device. */
  emoji: [string, string][];
  decimal?: [number, number, number];
}

export interface VerificationFlow {
  stage: VerificationStage;
  /** We sent the request (banner "Verify this session"), else it arrived from another device / user. */
  initiatedByMe: boolean;
  /** Verifying our own account's other device (the normal case), vs another user. */
  isSelf: boolean;
  otherUserId: string;
  otherDeviceId?: string;
  sas: SasState | null;
  /** Why it stopped (cancel code / message) when `stage === 'cancelled'`. */
  error: string | null;
}

export interface RecoveryState {
  busy: 'unlock' | 'restore' | 'setup' | 'import' | null;
  progress: { imported: number; total: number } | null;
  lastRestore: { imported: number; total: number } | null;
  error: string | null;
  /**
   * Set with `error` when `unlockWithRecoveryKey` failed on the key itself (`RecoveryKeyError.kind`): `none` = the
   * account has no recovery key, `invalid` = not a recovery key / passphrase shape, `wrong` = does not open the
   * secret storage, `unusable` = it opens secret storage but the identity keys are not stored under it (verify from
   * another device instead). Undefined for any other failure (network, backup) so the UI never matches message text.
   */
  errorKind?: 'none' | 'invalid' | 'wrong' | 'unusable';
  /**
   * The session is verified but the key backup stayed locked (`UnlockResult.restoreError`): set by an unlock whose
   * restore failed (any reason) and by a restore that failed on the key (`cancelled` / `wrong-key` / `no-key`; a
   * plain `failed` restore sets `error` instead). Kept while a retry / reset runs and when it fails; cleared by a
   * successful restore, a successful `setupRecovery` or a new unlock. The recovery dialog renders it as `locked`.
   */
  backupLocked: { reason: RestoreFailureReason; message: string } | null;
  /** Result of the last successful `importKeysFromFile` (sessions accepted / in the file). */
  lastImport: KeyImportResult | null;
  /**
   * Why `importKeysFromFile` failed: `passphrase` = the file's HMAC does not match (wrong passphrase), `format` = not
   * an Element key export, `failed` = the engine refused / anything else. `message` is user text.
   */
  importError: { kind: 'passphrase' | 'format' | 'failed'; message: string } | null;
}

export interface PendingPrompt {
  /**
   * `password`: the server wants `m.login.password` for a UIA stage (answer with the password);
   * `recovery-key`: the SDK needs the secret storage key (answer with the key / passphrase);
   * `sso`: SSO-only servers (704.chat): the `m.login.sso` fallback page opened in a popup (`url`; `popupBlocked`
   * when it could not open, so show the link). Render "Finish signing in in the window that opened" and a
   * "Done" button that calls `answerPrompt('done')`; the prompt also closes by itself when the popup reports back.
   */
  kind: 'password' | 'recovery-key' | 'sso';
  /** Human text for the dialog ("Confirm your password to upload your keys"). */
  message: string;
  /** `recovery-key` only: the secret being read (`m.megolm_backup.v1`, ...), when the SDK said. */
  secretName?: string;
  /** `recovery-key` only: a recovery key was already entered but does not open this secret (another 4S key). */
  differentKey?: boolean;
  /** `sso` only: the fallback page URL. */
  url?: string;
  /** `sso` only: the popup was blocked; the UI should offer `url` as a link. */
  popupBlocked?: boolean;
}

export interface SecurityState {
  /** The crypto engine runs for this session (false before bind, or when it failed: see `cryptoError`). */
  cryptoReady: boolean;
  cryptoError: string | null;
  /** Null until the first `refresh()` completes. */
  status: OwnDeviceStatus | null;
  hint: SecurityHint;
  verification: VerificationFlow | null;
  recovery: RecoveryState;
  prompt: PendingPrompt | null;
  newRecoveryKey: string | null;
  /** A key file was imported this session (`importKeysFromFile` succeeded); cleared on logout only. */
  keysImported: boolean;
  /** See the header: verified, the backup key is unreachable on this device (re-checked on every refresh). */
  historyUnavailable: boolean;
  /**
   * The reachability check behind `historyUnavailable` has resolved for the current state (a verified device with
   * a locked backup). False during the gossip grace: the banner stays quiet until it is true, so it never flashes
   * "unlock" before settling on E2 (or before the backup key arrives from the other device).
   */
  historyChecked: boolean;
  /**
   * Room keys this device still has to upload to the key backup (`CryptoEvent.KeyBackupSessionsRemaining`);
   * null until the first upload round. The SDK starts uploading up to 10 s after the backup is enabled, so a
   * logout right after `setupRecovery` can leave keys out of the backup: show "Backing up N keys" while > 0.
   */
  backupRemaining: number | null;
  /** Bumps on every change the UI might care about (status, flow, prompt). */
  version: number;

  /** Re-read this device's status from the SDK. */
  refresh(): Promise<void>;
  /** Banner button: ask the account's other devices (Element, another codec) to verify this one by emoji. */
  startSelfVerification(): Promise<void>;
  /** Accept an incoming request (`verification.initiatedByMe === false`, stage 'requested'). */
  acceptVerification(): Promise<void>;
  /** Cancel / decline the in-flight request. */
  cancelVerification(): Promise<void>;
  /** The emoji match. */
  confirmSas(): Promise<void>;
  /** The emoji do not match (cancels with `m.mismatched_sas`). */
  mismatchSas(): void;
  /** Drop a finished / cancelled flow from the state. */
  dismissVerification(): void;
  /**
   * Recovery key (or passphrase) typed by the user: verifies this device from secret storage and restores backup.
   * Resolves true once verified, even when the restore failed (`recovery.backupLocked` then says why).
   */
  unlockWithRecoveryKey(input: string): Promise<boolean>;
  /**
   * Pull room keys from the key backup (the decryption key must be known: after SAS or unlock, or its 4S copy must
   * open with a cached key; nobody is asked). A key failure sets `backupLocked`, anything else `error`.
   */
  restoreFromBackup(): Promise<void>;
  /**
   * The explicit "I have a different recovery key": the only place a recovery-key prompt can appear. Registers the
   * prompt, restores from the backup (the SDK asks for the 4S key its copy is under), unregisters it again.
   */
  restoreWithDifferentKey(): Promise<void>;
  /** First-time setup (or `reset`): creates cross-signing, a recovery key and a key backup. Resolves with the key. */
  setupRecovery(opts?: { passphrase?: string; reset?: boolean }): Promise<string | null>;
  /**
   * Import an Element key export (the file's text + its passphrase): busy 'import' with `progress`, then
   * `lastImport` (true) or `importError` (false). `backupLocked` is kept: the backup itself stays locked.
   */
  importKeysFromFile(fileText: string, passphrase: string): Promise<boolean>;
  dismissRecoveryKey(): void;
  /** Answer the current `prompt` (null = cancel). */
  answerPrompt(value: string | null): void;
}

const idleRecovery: RecoveryState = { busy: null, progress: null, lastRestore: null, error: null, backupLocked: null, lastImport: null, importError: null };

/** What to show the user given a status snapshot. */
export function securityHint(status: OwnDeviceStatus | null): SecurityHint {
  if (!status) return null;
  // No identity and no recovery key: first-time setup. With a recovery key but no identity (AC-E5-5: a reset
  // account, or keys created by another client), the key is the way in: `unlockWithRecoveryKey` bootstraps
  // cross-signing from (or into) secret storage.
  if (!status.hasCrossSigningKeys) return status.secretStorageReady ? 'unlock' : 'setup';
  if (!status.verified) return 'verify';
  if (status.backup.version && !status.backup.keyCached) return 'unlock';
  return null;
}

function describe(e: unknown): string {
  return e instanceof Error ? e.message : String(e);
}

/** The live request/verifier behind `verification` (not in the store: not serialisable, not for rendering). */
let live: { request: VerificationRequest; verifier?: Verifier; sas?: ShowSasCallbacks; off: () => void } | null = null;
let pendingPromptResolve: ((value: string | null) => void) | null = null;

function ask(kind: PendingPrompt['kind'], message: string, extra: Partial<PendingPrompt> = {}): Promise<string | null> {
  pendingPromptResolve?.(null);
  return new Promise((resolve) => {
    pendingPromptResolve = resolve;
    useSecurityStore.setState((s) => ({ prompt: { kind, message, ...extra }, version: s.version + 1 }));
  });
}

/** Clear the current prompt without answering it (the flow finished on its own, e.g. the SSO popup reported back). */
function dropPrompt(): void {
  pendingPromptResolve = null;
  useSecurityStore.setState((s) => (s.prompt ? { prompt: null, version: s.version + 1 } : s));
}

const uia: UiaOptions = {
  password: () => ask('password', 'Confirm your password to publish your encryption keys'),
  sso: async (url, popupBlocked) => {
    const answer = await ask('sso', popupBlocked ? 'Open the sign-in page, finish signing in, then come back' : 'Finish signing in in the window that opened', { url, popupBlocked });
    if (answer === null) throw new Error('Authentication cancelled');
  },
};

function flowFrom(request: VerificationRequest, prev?: VerificationFlow | null): VerificationFlow {
  const stage: VerificationStage =
    request.phase === VerificationPhase.Done
      ? 'done'
      : request.phase === VerificationPhase.Cancelled
        ? 'cancelled'
        : request.phase === VerificationPhase.Started
          ? (prev?.sas ? 'sas' : 'started')
          : request.phase === VerificationPhase.Ready
            ? 'ready'
            : 'requested';
  return {
    stage,
    initiatedByMe: request.initiatedByMe,
    isSelf: request.isSelfVerification,
    otherUserId: request.otherUserId,
    otherDeviceId: request.otherDeviceId ?? prev?.otherDeviceId, // the SDK drops it once the request is done
    sas: stage === 'sas' ? (prev?.sas ?? null) : null,
    error:
      stage === 'cancelled'
        ? (prev?.error ?? (request.cancellationCode === 'm.mismatched_sas' ? 'The emoji did not match' : request.cancellationCode === 'm.timeout' ? 'The request timed out' : `Cancelled (${request.cancellationCode ?? 'unknown'})`))
        : null,
  };
}

function setFlow(flow: VerificationFlow | null): void {
  useSecurityStore.setState((s) => ({ verification: flow, version: s.version + 1 }));
}

/** Track a request: mirror its phases, start SAS when both sides are ready, surface the emoji. */
function trackRequest(request: VerificationRequest): void {
  live?.off();
  let verifierAttached = false;
  let starting = false;
  const attachVerifier = (verifier: Verifier): void => {
    if (verifierAttached) return;
    verifierAttached = true;
    live!.verifier = verifier;
    verifier.on(VerifierEvent.ShowSas, (sas) => {
      live!.sas = sas;
      const prev = useSecurityStore.getState().verification;
      setFlow({ ...flowFrom(request, prev), stage: 'sas', sas: { emoji: sas.sas.emoji ?? [], decimal: sas.sas.decimal } });
    });
    verifier.on(VerifierEvent.Cancel, (e) => {
      const prev = useSecurityStore.getState().verification;
      setFlow({ ...flowFrom(request, prev), stage: 'cancelled', error: e instanceof Error ? e.message : (prev?.error ?? 'Cancelled by the other device') });
    });
    verifier.verify().catch(() => {
      /* reported through VerifierEvent.Cancel / the request phase */
    });
  };
  const onChange = (): void => {
    const prev = useSecurityStore.getState().verification;
    setFlow(flowFrom(request, prev));
    if (request.verifier) attachVerifier(request.verifier);
    if (request.phase === VerificationPhase.Ready && !request.verifier && !starting) {
      starting = true;
      startSas(request)
        .then(attachVerifier)
        .catch((e: unknown) => setFlow({ ...flowFrom(request, prev), stage: 'cancelled', error: describe(e) }));
    }
    if (request.phase === VerificationPhase.Done) {
      void useSecurityStore.getState().refresh();
      healKeyStorage();
    }
  };
  request.on(VerificationRequestEvent.Change, onChange);
  live = { request, off: () => request.off(VerificationRequestEvent.Change, onChange) };
  onChange();
}

export const useSecurityStore = create<SecurityState>((set, get) => ({
  cryptoReady: false,
  cryptoError: null,
  status: null,
  hint: null,
  verification: null,
  recovery: idleRecovery,
  prompt: null,
  newRecoveryKey: null,
  keysImported: false,
  historyUnavailable: false,
  historyChecked: false,
  backupRemaining: null,
  version: 0,

  async refresh() {
    if (!isCryptoReady()) {
      set((s) => ({ cryptoReady: false, cryptoError: getCryptoError(), status: null, hint: null, version: s.version + 1 }));
      return;
    }
    try {
      const status = await getOwnDeviceStatus();
      if (!status.verified) {
        verifiedSince = null;
        sawUnverified = true;
      } else if (verifiedSince === null) {
        // Verified on this page (emoji, unlock): give gossip its grace. Already verified at the first status of
        // the page load: no secret request is in flight (the engine only asks when a verification completes).
        verifiedSince = sawUnverified ? Date.now() : Date.now() - GOSSIP_GRACE_MS;
      }
      set((s) => ({ cryptoReady: true, cryptoError: null, status, hint: securityHint(status), version: s.version + 1 }));
      checkHistoryReachable();
    } catch (e) {
      console.warn('[security] status refresh failed', e);
    }
  },

  async startSelfVerification() {
    try {
      const request = await requestOwnUserVerification();
      trackRequest(request);
    } catch (e) {
      setFlow({ stage: 'cancelled', initiatedByMe: true, isSelf: true, otherUserId: '', sas: null, error: describe(e) });
    }
  },

  async acceptVerification() {
    if (!live) return;
    try {
      await live.request.accept();
    } catch (e) {
      setFlow({ ...flowFrom(live.request, get().verification), stage: 'cancelled', error: describe(e) });
    }
  },

  async cancelVerification() {
    if (!live) return;
    try {
      await live.request.cancel({ reason: 'User cancelled', code: 'm.user' });
    } catch {
      /* already over */
    }
  },

  async confirmSas() {
    const sas = live?.sas;
    if (!sas) return;
    try {
      await sas.confirm();
    } catch (e) {
      if (live) setFlow({ ...flowFrom(live.request, get().verification), stage: 'cancelled', error: describe(e) });
    }
  },

  mismatchSas() {
    live?.sas?.mismatch();
  },

  dismissVerification() {
    live?.off();
    live = null;
    setFlow(null);
  },

  async unlockWithRecoveryKey(input) {
    set((s) => ({ recovery: { ...idleRecovery, busy: 'unlock' }, version: s.version + 1 }));
    try {
      const result = await unlockWithRecoveryKey(input, { uia, onProgress: (p) => reportProgress(p) });
      dropPrompt();
      // Verified either way; a failed restore leaves the backup locked (the dialog shows E2: import a key file, ...).
      set((s) => ({ recovery: { ...idleRecovery, lastRestore: result.restore, backupLocked: result.restoreError ?? null }, version: s.version + 1 }));
      healKeyStorage();
      await get().refresh();
      return true;
    } catch (e) {
      dropPrompt();
      const errorKind = e instanceof RecoveryKeyError ? e.kind : undefined;
      set((s) => ({ recovery: { ...idleRecovery, error: describe(e), ...(errorKind ? { errorKind } : {}) }, version: s.version + 1 }));
      return false;
    }
  },

  async restoreFromBackup() {
    if (get().recovery.busy) return;
    const locked = get().recovery.backupLocked;
    set((s) => ({ recovery: { ...idleRecovery, busy: 'restore', backupLocked: locked }, version: s.version + 1 }));
    const { restore, restoreError } = await attemptRestoreFromBackup((p) => reportProgress(p));
    dropPrompt();
    if (restore) {
      set((s) => ({ recovery: { ...idleRecovery, lastRestore: restore }, version: s.version + 1 }));
      healKeyStorage();
    }
    else if (restoreError && restoreError.reason !== 'failed') set((s) => ({ recovery: { ...idleRecovery, backupLocked: restoreError }, version: s.version + 1 }));
    else set((s) => ({ recovery: { ...idleRecovery, error: restoreError?.message ?? 'Restore failed', backupLocked: locked }, version: s.version + 1 }));
    await get().refresh();
  },

  async restoreWithDifferentKey() {
    if (get().recovery.busy) return;
    setSecretStorageKeyPrompt(
      (_keyInfo, _keyId, context) => ask('recovery-key', recoveryPromptMessage(context), { secretName: context.secretName, differentKey: context.differentKey }),
      promptOptions,
    );
    try {
      await get().restoreFromBackup();
    } finally {
      setSecretStorageKeyPrompt(null);
    }
  },

  async importKeysFromFile(fileText, passphrase) {
    if (get().recovery.busy) return false;
    const locked = get().recovery.backupLocked;
    set((s) => ({ recovery: { ...idleRecovery, busy: 'import', backupLocked: locked }, version: s.version + 1 }));
    try {
      const result = await importRoomKeysFromFile(fileText, passphrase, (p) => reportProgress(p));
      set((s) => ({ recovery: { ...idleRecovery, backupLocked: locked, lastImport: result }, keysImported: true, version: s.version + 1 }));
      healKeyStorage();
      return true;
    } catch (e) {
      const importError = e instanceof KeyExportError ? { kind: e.kind, message: e.message } : { kind: 'failed' as const, message: describe(e) };
      set((s) => ({ recovery: { ...idleRecovery, backupLocked: locked, importError }, version: s.version + 1 }));
      return false;
    }
  },

  async setupRecovery(opts = {}) {
    // A reset from the locked state keeps `backupLocked` until it succeeds (a failed / cancelled reset returns there).
    const locked = get().recovery.backupLocked;
    set((s) => ({ recovery: { ...idleRecovery, busy: 'setup', backupLocked: locked }, newRecoveryKey: null, version: s.version + 1 }));
    try {
      const key = await setupRecovery({ ...opts, uia });
      dropPrompt();
      set((s) => ({ recovery: idleRecovery, newRecoveryKey: key, version: s.version + 1 }));
      await get().refresh();
      return key;
    } catch (e) {
      dropPrompt();
      set((s) => ({ recovery: { ...idleRecovery, error: describe(e), backupLocked: locked }, version: s.version + 1 }));
      return null;
    }
  },

  dismissRecoveryKey() {
    set((s) => ({ newRecoveryKey: null, version: s.version + 1 }));
  },

  answerPrompt(value) {
    const resolve = pendingPromptResolve;
    pendingPromptResolve = null;
    set((s) => ({ prompt: null, version: s.version + 1 }));
    resolve?.(value);
  },
}));

/** Text of a `recovery-key` prompt: "this is a different key" when the one already entered does not open it. */
function recoveryPromptMessage(context: SecretStorageKeyPromptContext): string {
  const backup = context.secretName === 'm.megolm_backup.v1';
  if (context.differentKey) {
    return backup
      ? 'Your key backup uses a different recovery key. Enter that key to unlock your older messages'
      : 'This secret is protected by a different recovery key. Enter that key to continue';
  }
  return backup ? 'Enter your recovery key to unlock your older messages' : 'Enter your recovery key to unlock your encryption keys';
}

// ---------------------------------------------------------------------------
// Self-heal and backup reachability
// ---------------------------------------------------------------------------

/**
 * How long after this device became verified (or, already verified, after the first status of this page load)
 * the backup key may still arrive by gossip: the Rust engine requests missing secrets (`m.secret.request`) from
 * our other devices when a self-verification completes, and their answer lands as `KeyBackupDecryptionKeyCached`.
 */
export const GOSSIP_GRACE_MS = 10_000;

let verifiedSince: number | null = null;
/** This page saw the device unverified (so a later `verified` is a verification that just happened here). */
let sawUnverified = false;
let historyTimer: ReturnType<typeof setTimeout> | null = null;
let historyCheckRunning = false;
let healRunning: Promise<void> | null = null;

/** Re-store locally held secrets under the default 4S key (`syncSecretsToDefaultKey`), silently, one at a time. */
function healKeyStorage(): void {
  if (healRunning) return;
  healRunning = syncSecretsToDefaultKey()
    .then((healed) => {
      if (healed.length) console.info('[security] re-stored under the default secret storage key:', healed.join(', '));
    })
    .catch((e: unknown) => console.warn('[security] key storage self-heal failed', e))
    .finally(() => {
      healRunning = null;
    });
}

function setHistory(unavailable: boolean, checked: boolean): void {
  useSecurityStore.setState((s) =>
    s.historyUnavailable === unavailable && s.historyChecked === checked ? s : { historyUnavailable: unavailable, historyChecked: checked, version: s.version + 1 },
  );
}

/**
 * Decide `historyUnavailable` from the latest status: only a verified device with a server backup and no backup
 * key qualifies, and only once `GOSSIP_GRACE_MS` passed since it became verified; then the 4S copy of the backup
 * key decides (under the default key = the recovery key opens it: not unavailable).
 */
function checkHistoryReachable(): void {
  const status = useSecurityStore.getState().status;
  const candidate = !!status && status.verified && !!status.backup.version && !status.backup.keyCached;
  if (!candidate || verifiedSince === null) {
    setHistory(false, false);
    return;
  }
  const wait = verifiedSince + GOSSIP_GRACE_MS - Date.now();
  if (wait > 0) {
    setHistory(false, false);
    if (!historyTimer) {
      historyTimer = setTimeout(() => {
        historyTimer = null;
        checkHistoryReachable();
      }, wait);
    }
    return;
  }
  if (historyCheckRunning) return;
  historyCheckRunning = true;
  isBackupSecretOnDefaultKey()
    .then((onDefault) => {
      const now = useSecurityStore.getState().status;
      const still = !!now && now.verified && !!now.backup.version && !now.backup.keyCached;
      setHistory(still && !onDefault, still);
    })
    .catch((e: unknown) => {
      console.warn('[security] backup reachability check failed', e);
      setHistory(false, true); // unknown: fall back to the plain `unlock` banner rather than none at all
    })
    .finally(() => {
      historyCheckRunning = false;
    });
}

function reportProgress(p: ImportRoomKeyProgressData): void {
  if (p.stage !== 'load_keys') return;
  useSecurityStore.setState((s) => ({
    recovery: { ...s.recovery, progress: { imported: p.successes, total: p.total } },
    version: s.version + 1,
  }));
}

// ---------------------------------------------------------------------------
// Session wiring
// ---------------------------------------------------------------------------

let unbind: (() => void) | null = null;
/** Options of the recovery-key prompt `restoreWithDifferentKey` registers (the bound client's default key id). */
let promptOptions: SecretStorageKeyPromptOptions = {};

/** Subscribe to crypto events for a started client and take the first status snapshot. Idempotent per client. */
export function bindSecurity(client: MatrixClient): void {
  unbindSecurity();
  const store = useSecurityStore.getState();
  // One ask only: no session-wide recovery-key prompt. `restoreWithDifferentKey` registers it for its own call;
  // the default key id makes that prompt ask for the account's key when the secret is under it.
  setSecretStorageKeyPrompt(null);
  promptOptions = { defaultKeyId: () => client.secretStorage.getDefaultKeyId() };
  const refresh = (): void => void useSecurityStore.getState().refresh();
  const onRequest = (request: VerificationRequest): void => {
    // One flow at a time: a new incoming request replaces whatever is tracked. An active flow is cancelled first
    // (AC-E4-7: the latest request wins, the stale one never leaves a dangling dialog); a finished one is dropped.
    const current = useSecurityStore.getState().verification;
    const active = !!current && current.stage !== 'done' && current.stage !== 'cancelled';
    // The Rust engine refuses a second concurrent request from the same user: it arrives already cancelled. Keep
    // the live flow then (tracking the dead one would lose both).
    if (active && request.phase === VerificationPhase.Cancelled) return;
    if (active) {
      const stale = live;
      live = null;
      stale?.off();
      void stale?.request.cancel().catch(() => {
        /* already gone */
      });
    }
    trackRequest(request);
  };
  const onBackupKeyCached = (): void => {
    // The device that verified us (or the unlock flow) just handed us the backup key: fetch old room keys.
    void useSecurityStore.getState().restoreFromBackup();
  };
  // Cross-signing / backup state is only known once the first /sync (and the key query it triggers) landed.
  const onSync = (state: SyncState): void => {
    if (state === SyncState.Prepared) refresh();
  };
  const offRequest = onVerificationRequestReceived(onRequest);
  client.on(ClientEvent.Sync, onSync);
  client.on(CryptoEvent.KeysChanged, refresh);
  client.on(CryptoEvent.UserTrustStatusChanged, refresh);
  client.on(CryptoEvent.DevicesUpdated, refresh);
  const onRemaining = (remaining: number): void => {
    useSecurityStore.setState((s) => (s.backupRemaining === remaining ? s : { backupRemaining: remaining, version: s.version + 1 }));
  };
  client.on(CryptoEvent.KeyBackupStatus, refresh);
  client.on(CryptoEvent.KeyBackupSessionsRemaining, onRemaining);
  client.on(CryptoEvent.KeyBackupDecryptionKeyCached, onBackupKeyCached);
  unbind = () => {
    offRequest();
    client.off(ClientEvent.Sync, onSync);
    client.off(CryptoEvent.KeysChanged, refresh);
    client.off(CryptoEvent.UserTrustStatusChanged, refresh);
    client.off(CryptoEvent.DevicesUpdated, refresh);
    client.off(CryptoEvent.KeyBackupStatus, refresh);
    client.off(CryptoEvent.KeyBackupSessionsRemaining, onRemaining);
    client.off(CryptoEvent.KeyBackupDecryptionKeyCached, onBackupKeyCached);
    setSecretStorageKeyPrompt(null);
    promptOptions = {};
  };
  void store.refresh();
}

export function unbindSecurity(): void {
  unbind?.();
  unbind = null;
}

/** Logout: forget flows, prompts and status. */
export function resetSecurity(): void {
  live?.off();
  live = null;
  verifiedSince = null;
  sawUnverified = false;
  if (historyTimer) clearTimeout(historyTimer);
  historyTimer = null;
  pendingPromptResolve?.(null);
  pendingPromptResolve = null;
  useSecurityStore.setState((s) => ({
    cryptoReady: false,
    cryptoError: null,
    status: null,
    hint: null,
    verification: null,
    recovery: idleRecovery,
    prompt: null,
    newRecoveryKey: null,
    keysImported: false,
    historyUnavailable: false,
    historyChecked: false,
    backupRemaining: null,
    version: s.version + 1,
  }));
}

/** Selector: the banner hint (`'setup' | 'verify' | 'unlock' | null`). */
export function useSecurityHint(): SecurityHint {
  return useSecurityStore((s) => s.hint);
}
